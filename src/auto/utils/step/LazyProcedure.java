	public String prettyPrintProcedureTest(String dataTestID) {
		StringBuilder stb = new StringBuilder();
		stb.append("\nTest: " + dataTestID);
		return prettyPrintProcedure(stb);
	}
	
	public String prettyPrintProcedure() {
		return prettyPrintProcedure(new StringBuilder());
	}
	
	private String prettyPrintProcedure(StringBuilder stb) {
		String[] stepStringArray = Step.prettyPrintProcedure(getStepList());
		for (int i = 0 ; i < stepStringArray.length ; i++) {
			final String stepString = stepStringArray[i];
			stb.append("\r\n" + (1 + i) + stepString);
		}
		return stb.toString();
	}
	
	/**
	 * Splits tableField strings that are separated by a point ('.') or if no point
	 * is present, attempts to resolve it by looking through the passed
	 * ActivityDefinition.
	 * 
	 * @see {@link ActivityDefinitionUtils#resolveIpFunction(ActivityDefinition, String)}
	 * @param validationActivity
	 *            The activity assist in resolving the tableField String
	 * @param tableField
	 *            The tableField String to be resolved
	 * @return String String array containing two values representing table and
	 *         field
	 */
	public static String[] resolveTableField(ActivityDefinition validationActivity, String tableField) {
		String[] resolved = new String[2];
		
		if (tableField.contains(".")) {
			String[] temp = tableField.split("\\.");
			
			if (temp.length != 2) {
				throw new IllegalArgumentException("tableField value was not of format \"table.field\"");
			}
				
			resolved = temp;
		}else {
			resolved = ActivityDefinitionUtils.resolveIpFunction(validationActivity, tableField);
		}
		
		return resolved;
	}
	
