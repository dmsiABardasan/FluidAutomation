	public void assertExpectedChildren(int expectedNumberOfChildren, ActivityVariant... validateActivity) {
		String[] services = new String[validateActivity.length];
		String[] variants = new String[validateActivity.length];
		for (int i = 0 ; i < validateActivity.length ; i++) {
			services[i] = validateActivity[i].getService();
			variants[i] = validateActivity[i].getName();
		}
		Step.assertExpectedChildren(getChildList(), services, variants, expectedNumberOfChildren);
	}
	
	/**
	 * Gets the first child in the child list that has an ipservice equal to the param.
	 * Caution, there could potentially contain more than one child with the same service
	 * 
	 * @throws IllegalArgumentException If there were multiple children with the same service
	 * @throws NullPointerException If there were no children found with the given service
	 * @param ipService
	 * @return ChildActivityDefinition
	 */
	public ChildActivityDefinition cutChildFromList(String ipService) {
		return cutChildFromList(ipService, null) ;
	}
	
	public ChildActivityDefinition cutChildFromList(ActivityVariant validateActivity) {
		return cutChildFromList(validateActivity.getService(), validateActivity.getName());
	}
	
	public ChildActivityDefinition cutChildFromList(final String service, final String variantName) {
		ChildActivityDefinition foundChild = null;
		for (ChildActivityDefinition childActivityDef : getChildList()) {
			final String childService = childActivityDef.getService();
			final String childActivity = childActivityDef.getModel().getActivity();
			
			boolean found = service != null || variantName != null;
			
			if (variantName != null && found) {
				found = variantName.equals(childActivity);
			}
			if (service != null && found) {
				found = service.equals(childService);
			}
			
			if (found) {
				if (foundChild != null) {
					throw new IllegalArgumentException("There were multiple children with the same cut criteria.");
				} else {
					foundChild = childActivityDef;
				}
			}
		}
		if (foundChild == null) {
			throw new NullPointerException("No ChildActivityDefinitions were found in the child list equal to the provided criteria.");
		}
		
		getChildList().remove(foundChild);
		
		return foundChild;
	}
	
	public Step stepLaunch(ActivityDefinition validationActivity, ValidationTypeEnum validationType, String tableField) {
		String[] resolvedTableField = resolveTableField(validationActivity, tableField);
		Step step = new Step(validationType, resolvedTableField[0], resolvedTableField[1]).setLaunch(true);
		
		executeStep(validationActivity, step);
		
		return step;
	}
	
	public Step stepEvent(FluidEvent fluidEvent, ActivityDefinition validationActivity, ValidationTypeEnum validationType, String tableField) {
		String[] resolvedTableField = resolveTableField(validationActivity, tableField);
		Step step = new Step(validationType, resolvedTableField[0], resolvedTableField[1]).setFluidEvent(fluidEvent);

		executeStep(validationActivity, step);
		
		return step;
	}
	
	public Step stepEvent(ActivityDefinition validationActivity, ValidationTypeEnum validationType, FluidEvent fluidEvent, String tableField, Object value) {
		String[] resolvedTableField = resolveTableField(validationActivity, tableField);
		Step step = new Step(validationType, resolvedTableField[0], resolvedTableField[1], value).setFluidEvent(fluidEvent);

		executeStep(validationActivity, step);
		
		return step;
	}
	
	/**
	 * Creates a new Step based on the passed arguments without assigning an value,
	 * then {@link #executeStep(ActivityDefinition, Step) executes the Step}
	 * 
	 * @param launch
	 *            Determines whether you want to forcefully run the specified
	 *            tableField as a ChildActivityDefinition (true) or not (false)
	 * @param recordIndex
	 *            Integer index position of the record in the DataSourceDefinition
	 *            you wish to manipulate (null refers to the 'currentRow' of the
	 *            DataSourceDefinition)
	 * @param validationActivity
	 *            The ActivityDefinition to have the Step run against
	 * @param validationType
	 *            How the response for the Step is to be validated
	 * @param tableField
	 *            The tableField to be validated
	 *            ({@link #resolveTableField(ActivityDefinition, String) lenient
	 *            tableField resolution})
	 * @return The created and executed step
	 */
	public Step step(boolean launch, Integer recordIndex, ActivityDefinition validationActivity, ValidationTypeEnum validationType, String tableField) {
		String[] resolvedTableField = resolveTableField(validationActivity, tableField);
		Step step = new Step(validationType, resolvedTableField[0], resolvedTableField[1]).setRecordIndex(recordIndex).setLaunch(launch);

		executeStep(validationActivity, step);
		
		return step;
	}
	
	/**
	 * Creates a new Step based on the passed arguments then
	 * {@link #executeStep(ActivityDefinition, Step) executes the Step}
	 * 
	 * @param launch
	 *            Determines whether you want to forcefully run the specified
	 *            tableField as a ChildActivityDefinition (true) or not (false)
	 * @param recordIndex
	 *            Integer index position of the record in the DataSourceDefinition
	 *            you wish to manipulate (null refers to the 'currentRow' of the
	 *            DataSourceDefinition)
	 * @param validationActivity
	 *            The ActivityDefinition to have the Step run against
	 * @param validationType
	 *            How the response for the Step is to be validated
	 * @param tableField
	 *            The tableField to be validated
	 *            ({@link #resolveTableField(ActivityDefinition, String) lenient
	 *            tableField resolution})
	 * @param value
	 *            The value to be passed to the tableField
	 * @return The created and executed step
	 */
	public Step step(boolean launch, Integer recordIndex, ActivityDefinition validationActivity, ValidationTypeEnum validationType, String tableField, Object value) {
		String[] resolvedTableField = resolveTableField(validationActivity, tableField);
		Step step = new Step(validationType, resolvedTableField[0], resolvedTableField[1], value).setRecordIndex(recordIndex).setLaunch(launch);
		
		executeStep(validationActivity, step);

		return step;
	}
	
